RCON = [0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]

def xtime(b):
    res = (b << 1) & 0xff
    if b & 0x80:
        res ^= 0x1b
    return res

def add_round_key(state, key):
    return [s ^ k for s, k in zip(state, key)]

def sub_bytes(state):
    return [SBOX[b] for b in state]

def shift_rows(s):
    # s is 16 bytes, column-major:
    # row 0: 0, 4, 8, 12
    # row 1: 1, 5, 9, 13
    # row 2: 2, 6, 10, 14
    # row 3: 3, 7, 11, 15
    return [
        s[0],  s[5],  s[10], s[15],  # col 0
        s[4],  s[9],  s[14], s[3],   # col 1
        s[8],  s[13], s[2],  s[7],   # col 2
        s[12], s[1],  s[6],  s[11]   # col 3
    ]

def mix_single_column(c):
    c0, c1, c2, c3 = c[0], c[1], c[2], c[3]
    r0 = xtime(c0) ^ (xtime(c1) ^ c1) ^ c2 ^ c3
    r1 = c0 ^ xtime(c1) ^ (xtime(c2) ^ c2) ^ c3
    r2 = c0 ^ c1 ^ xtime(c2) ^ (xtime(c3) ^ c3)
    r3 = (xtime(c0) ^ c0) ^ c1 ^ c2 ^ xtime(c3)
    return [r0, r1, r2, r3]

def mix_columns(s):
    res = []
    for c in range(4):
        col = s[c*4 : (c+1)*4]
        res.extend(mix_single_column(col))
    return res

def key_expansion(key_in, round_num):
    w = [key_in[i*4 : (i+1)*4] for i in range(4)]
    w3 = w[3]
    rot = [w3[1], w3[2], w3[3], w3[0]]
    sub = [SBOX[b] for b in rot]
    rcon_word = [RCON[round_num], 0x00, 0x00, 0x00]
    w0_next = [a ^ b ^ c for a, b, c in zip(w[0], sub, rcon_word)]
    w1_next = [a ^ b for a, b in zip(w[1], w0_next)]
    w2_next = [a ^ b for a, b in zip(w[2], w1_next)]
    w3_next = [a ^ b for a, b in zip(w[3], w2_next)]
    return w0_next + w1_next + w2_next + w3_next

def aes_128_encrypt(plaintext, master_key, verbose=False):
    state = add_round_key(plaintext, master_key)
    round_key = master_key
    if verbose:
        print(f"Round 0 State: {bytes(state).hex()}")

    for r in range(1, 10):
        state = sub_bytes(state)
        state = shift_rows(state)
        state = mix_columns(state)
        round_key = key_expansion(round_key, r)
        state = add_round_key(state, round_key)
        if verbose:
            print(f"Round {r} State: {bytes(state).hex()} (Key: {bytes(round_key).hex()})")

    # Round 10: MixColumns is omitted
    state = sub_bytes(state)
    state = shift_rows(state)
    round_key = key_expansion(round_key, 10)
    state = add_round_key(state, round_key)
    if verbose:
        print(f"Round 10 (Final) State: {bytes(state).hex()} (Key: {bytes(round_key).hex()})")

    return bytes(state)

